#!/usr/bin/env python3
"""Builds INSTALL-PROMPT.md: one self-contained prompt that embeds every file
needed to install pipeline-lite, so the user needs no clone or download.

Usage: scripts/build_install_prompt.py [--check]
  --check  exit 1 if INSTALL-PROMPT.md is missing or out of date
"""
import hashlib
import json
import os
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
OUT = REPO / "INSTALL-PROMPT.md"
# Not needed to install or run the plugin.
EXCLUDE_PREFIXES = ("tests/", "scripts/")
EXCLUDE_FILES = {"INSTALL-PROMPT.md"}
FENCE = "~~~~~"
EOF_MARK = "__PIPELINE_LITE_EOF__"

HEADER = """\
# Install prompt

Paste everything below the line into Claude Code on the machine where you want pipeline-lite.
It is self-contained: every file of the plugin is embedded below, so nothing is downloaded.
Claude writes the files, runs the installer and asks you only for the kb location and which projects to register.

<!-- Generated by scripts/build_install_prompt.py; do not edit by hand. -->

---

Install the "pipeline-lite" Claude Code plugin (version {version}, content id `{content_id}`) for my user-level Claude Code setup. Every file it needs is embedded at the end of this message, so don't clone or download anything. Do the steps below in order. Look before you change anything, and don't overwrite or delete existing files without asking me.

1. **Check the prerequisites.** Confirm that `claude`, `python3` and `git` are on PATH (the installer uses git for the local kb), and say whether `rg` is there (optional search fallback). If a required tool is missing, stop and tell me how to install it. This setup expects Linux or macOS with bash. On Windows, stop and tell me it needs WSL.

2. **Check the target directory.** The files go into `~/pipeline-lite`. If it doesn't exist, create it. If it exists, compare it with the manifest in step 4 and show me which files would change and which extra files are there. Ask before overwriting anything. Never delete files that aren't in the manifest.

3. **Write the files.** Write every file from the "Files" section below into `~/pipeline-lite`, at the path in its heading, byte for byte. The content is everything between the `{fence}` fence lines, ending with exactly one newline. Don't reformat, fix or shorten anything, even if it looks wrong. The safest way is a quoted heredoc per file, which keeps `$`, backticks and backslashes as they are:

   ```bash
   mkdir -p ~/pipeline-lite/kb/kb
   cat > ~/pipeline-lite/kb/kb/__init__.py <<'{eof}'
   <content>
   {eof}
   ```

   Several files per command is fine. Empty files are marked as such; create them with `: > <path>`. Then run `chmod +x` on every file marked executable.

   If I gave you this prompt as a file path instead of pasting it, extract the files mechanically instead of writing them by hand:

   ```bash
   python3 - <prompt-file> ~/pipeline-lite <<'PY'
   import os, re, sys
   text = open(sys.argv[1], encoding="utf-8").read()
   dest = os.path.expanduser(sys.argv[2])
   part = text.split("\\n## Files\\n", 1)[1]
   for m in re.finditer(r"^### `([^`]+)`([^\\n]*)\\n{fence}\\n(.*?)^{fence}$", part, re.S | re.M):
       path = os.path.join(dest, m.group(1))
       os.makedirs(os.path.dirname(path), exist_ok=True)
       with open(path, "w", encoding="utf-8", newline="") as f:
           f.write(m.group(3))
       if "executable" in m.group(2):
           os.chmod(path, 0o755)
   PY
   ```

4. **Verify the files.** Save the lines of the "Manifest" section below as `~/pipeline-lite/.manifest.sha256` and run `cd ~/pipeline-lite && sha256sum -c .manifest.sha256` (on macOS `shasum -a 256 -c .manifest.sha256`). Rewrite every file that fails and check again. Don't continue until all {count} files pass.

5. **Choose the knowledge base location.** The kb is a local-only git repo of markdown notes. The default is `~/agent-kb`, or `$KB_DIR` if that is set. Ask me whether the default is fine. If I pick another path, `KB_DIR` has to be set for the hooks too: offer to add it to the `env` block of `~/.claude/settings.json` and to my shell profile. Don't change either file without my yes.

6. **Preview the install.** Run `~/pipeline-lite/install.sh --dry-run` (add `--kb <path>` if I chose one) and show me the output. Point out anything that will be backed up, such as an existing `~/.local/bin/kb`. If the installer warns that the marketplace `agentic-pipeline-lite` is already registered from a different path, stop and show me the warning. Don't remove the old registration yourself.

7. **Install.** After I confirm, run the same command without `--dry-run`. The installer registers `~/pipeline-lite` as the local marketplace `agentic-pipeline-lite`, installs and enables `pipeline@agentic-pipeline-lite` at user scope, symlinks `bin/kb` into `~/.local/bin`, and creates the kb if it doesn't exist (git init, no remote, a `pre-push` hook that refuses every push). Re-running it is safe.

8. **Check PATH.** If `~/.local/bin` isn't on my PATH, tell me the one line to add to my shell profile and offer to add it. The hooks still work without it, but I won't be able to run `kb` myself.

9. **Register projects.** A project card is what makes a new session start with that project's context. Ask me which repos I want cards for, suggesting the git repo of the current directory if there is one. For each repo I pick, read its README and build files to propose a stack and the test/build commands, show me the proposal, and then run `kb project add <name> --path <dir> --stack "<stack>" --commands "<cmd>"` (one `--commands` per command). I can add more later the same way.

10. **Verify and report.** Confirm that `claude plugin list` shows `pipeline@agentic-pipeline-lite` as enabled, that `kb check` passes and that `kb project list` shows the cards. Then tell me in a few lines what you did, what you skipped and that I need to restart Claude Code. After the restart, sessions start with the project card and journal, and the skills appear as `/pipeline:kb`, `/pipeline:retro` and `/pipeline:status`. To update later, paste a newer version of this prompt. To uninstall, run `~/pipeline-lite/install.sh --uninstall`, which never deletes the kb.

It pairs with the lead workflow (https://github.com/hawt-cid/lead-workflow), whose task handoffs the session-start hook reads. If the `lead` skill isn't installed, mention that in one line, but don't install it.

Don't commit or push anything, and don't change any project repo. Never add a remote to the kb or send its contents to an external service. This install touches only `~/pipeline-lite`, the kb, `~/.local/bin/kb` and the Claude Code plugin registry, plus `~/.claude/settings.json` and my shell profile if I agreed to it in step 5 or 8.

## Manifest

```text
{manifest}
```

## Files
"""


def tracked_files():
    out = subprocess.run(["git", "ls-files", "-s"], cwd=REPO, check=True,
                         capture_output=True, text=True).stdout
    files = []
    for line in out.splitlines():
        meta, path = line.split("\t", 1)
        if path in EXCLUDE_FILES or path.startswith(EXCLUDE_PREFIXES):
            continue
        files.append((path, meta.split()[0] == "100755"))
    return sorted(files)


def build():
    files = tracked_files()
    version = json.loads((REPO / "plugin/.claude-plugin/plugin.json").read_text())["version"]
    manifest, sections = [], []
    for path, executable in files:
        data = (REPO / path).read_bytes()
        text = data.decode("utf-8")
        if text and not text.endswith("\n"):
            sys.exit(f"{path}: must end with a newline")
        if FENCE in text or EOF_MARK in text:
            sys.exit(f"{path}: contains {FENCE!r} or {EOF_MARK!r}")
        manifest.append(f"{hashlib.sha256(data).hexdigest()}  {path}")
        marks = [m for m, on in (("executable", executable), ("empty", not text)) if on]
        suffix = f" · {', '.join(marks)}" if marks else ""
        sections.append(f"### `{path}`{suffix}\n{FENCE}\n{text}{FENCE}\n")
    manifest_text = "\n".join(manifest)
    header = HEADER.format(
        version=version,
        content_id=hashlib.sha256(manifest_text.encode()).hexdigest()[:12],
        fence=FENCE,
        eof=EOF_MARK,
        count=len(files),
        manifest=manifest_text,
    )
    return header + "\n" + "\n".join(sections)


def main():
    content = build()
    if "--check" in sys.argv[1:]:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != content:
            print("INSTALL-PROMPT.md is out of date; run scripts/build_install_prompt.py", file=sys.stderr)
            sys.exit(1)
        return
    OUT.write_text(content, encoding="utf-8")
    print(f"wrote {OUT.relative_to(REPO)} ({len(content)} chars)")


if __name__ == "__main__":
    main()
